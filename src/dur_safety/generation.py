    if obj.get("finding_id") != gi.finding.finding_id:
        schema_errors.append("FINDING_ID_MISMATCH")
    if obj.get("risk_type") != gi.finding.risk_type:
        schema_errors.append("RISK_TYPE_MISMATCH")
    if isinstance(obj.get("summary"), str) and not obj["summary"].strip():
        schema_errors.append("EMPTY:summary")
    stmts = obj.get("evidence_statements")
    if not isinstance(stmts, list) or not all(
            isinstance(s, dict) and isinstance(s.get("statement"), str) and isinstance(s.get("evidence_ids"), list)
            and all(isinstance(i, str) for i in s["evidence_ids"]) for s in stmts):
        schema_errors.append("TYPE:evidence_statements")
        stmts = []

    cited = []
    for n, s in enumerate(stmts):
        inline, listed = extract_citations(s["statement"]), s["evidence_ids"]
        if not inline and not listed:
            cit_errors.append(f"STATEMENT_WITHOUT_CITATION:{n}")
        if len(listed) != len(set(listed)):
            cit_warnings.append(f"DUPLICATE_CITATION_IN_LIST:{n}")
        if set(inline) != set(listed):
            cit_errors.append(f"FIELD_INLINE_MISMATCH:{n}")
        cited += inline + listed
    for k in ["summary", "limitations", "review_note"]:
        outside = extract_citations(obj.get(k) if isinstance(obj.get(k), str) else "")
        if outside:
            cit_warnings.append(f"CITATION_OUTSIDE_STATEMENTS:{k}")
            cited += outside
    cited = list(dict.fromkeys(cited))
    invalid = [c for c in cited if c not in provided]
    if invalid:
        cit_errors.append("INVALID_EVIDENCE_ID:" + ",".join(invalid))
    if cited and not provided:
        cit_errors.append("CITATION_WITHOUT_EVIDENCE")
    if obj.get("evidence_status") in ("SUFFICIENT", "PARTIAL") and not cited:
        cit_errors.append("NO_CITATIONS")
    if obj.get("evidence_status") == "INSUFFICIENT" and stmts:
        cit_warnings.append("INSUFFICIENT_WITH_STATEMENTS")

    texts = [obj.get(k) for k in ["summary", "limitations", "review_note"] if isinstance(obj.get(k), str)]
    texts += [s["statement"] for s in stmts]
    flags = sorted({p for p in DIRECTIVE_PATTERNS for t in texts if re.search(p, t)})
    return schema_errors, cit_errors, cit_warnings, cited, flags

