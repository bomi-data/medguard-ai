def generate_explanation(finding: ScreeningFinding, llm_fn: Callable = call_llm,
                         retrieval_fn: Callable = retrieve_evidence, run_type="smoke"):
    rec = {"run_id": uuid.uuid4().hex[:12], "run_type": run_type, "created_at": datetime.now(timezone.utc).isoformat(),
           "finding_id": finding.finding_id, "finding_source": finding.finding_source, "risk_type": finding.risk_type,
           "target_item_seqs": finding.target_item_seqs, "screening_record": finding.screening_record,
           "dur_rule_texts": finding.dur_rule_texts, "prompt_version": PROMPT_VERSION,
           "output_schema_version": OUTPUT_SCHEMA_VERSION, "provider": GENERATION_CONFIG["provider"],
           "model": GENERATION_CONFIG["model"], "system_prompt_sha256": SYSTEM_PROMPT_SHA256,
           "llm_called": False, "user_prompt": None, "user_prompt_sha256": None, "raw_response": None,
           "llm_error": None, "stop_reason": None, "usage": {}, "latency_s": None, "output": None,
           "schema_errors": [], "citation_errors": [], "citation_warnings": [], "cited_evidence_ids": [],
           "directive_flags": []}
    retrieval = retrieval_fn(finding)
    gi = prepare_evidence_context(retrieval, finding)
    rec.update({"retrieval_status": retrieval.status, "retrieval_reason": retrieval.reason,
                "retrieval_warnings": retrieval.warnings, "retrieval_method": retrieval.method,
                "retrieval_query": retrieval.query, "retrieval_query_components": retrieval.query_components,
                "candidate_info": retrieval.candidate_info, "n_retrieved": int(len(retrieval.results)),
                "evidence": [asdict(e) for e in gi.evidence], "evidence_ids": [e.evidence_id for e in gi.evidence],
                "dropped_evidence": gi.dropped_evidence, "evidence_errors": gi.evidence_errors})

    if gi.evidence_errors:
        rec.update(generation_status="EVIDENCE_INVALID", output=deterministic_no_evidence_output(gi, "EVIDENCE_INVALID"))
        return rec
    if not gi.evidence:
        reason = retrieval.reason or ("EMPTY_EVIDENCE" if retrieval.status in ("OK", "DEGRADED") else retrieval.status)
        rec.update(generation_status="NO_EVIDENCE", output=deterministic_no_evidence_output(gi, reason))
        return rec

    prompt = build_prompt(gi)
    rec.update(user_prompt=prompt["user"], user_prompt_sha256=prompt["user_prompt_sha256"], llm_called=True)
    try:
        resp = llm_fn(prompt["system"], prompt["user"])
    except Exception as e:  # noqa: BLE001 — llm_fn 구현 오류도 기록으로 남긴다
        resp = LLMResponse(None, GENERATION_CONFIG["provider"], GENERATION_CONFIG["model"], error=f"{type(e).__name__}: {str(e)[:300]}")
    rec.update(raw_response=resp.text, llm_error=resp.error, stop_reason=resp.stop_reason,
               usage=resp.usage, latency_s=resp.latency_s)
    if resp.error:
        rec["generation_status"] = "LLM_UNAVAILABLE" if resp.error.startswith("LLM_UNAVAILABLE") else "LLM_ERROR"
        return rec
    if not (resp.text or "").strip():
        rec["generation_status"] = "EMPTY_RESPONSE"
        return rec
    try:
        obj = json.loads(resp.text)
    except json.JSONDecodeError:
        rec["generation_status"] = "MALFORMED_RESPONSE"
        return rec
    s_err, c_err, c_warn, cited, flags = validate_output(obj, gi)
    rec.update(output=obj, schema_errors=s_err, citation_errors=c_err, citation_warnings=c_warn,
               cited_evidence_ids=cited, directive_flags=flags,
               generation_status="GENERATED" if not s_err and not c_err else "INVALID_OUTPUT")
    return rec
