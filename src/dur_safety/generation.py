def validate_evidence_rows(res, finding):
    """04 결과 row가 corpus 원본과 일치하는지 검사. 반환: 오류 목록"""
    errors = []
    missing_cols = [c for c in EVIDENCE_REQUIRED if c not in res.columns]
    if missing_cols:
        return [{"row": None, "error": "MISSING_COLUMNS", "detail": missing_cols}]
    for i, r in enumerate(res.to_dict("records")):
        empty = [c for c in EVIDENCE_REQUIRED if r.get(c) is None or (isinstance(r.get(c), float) and pd.isna(r.get(c)))]
        if empty:
            errors.append({"row": i, "error": "MISSING_FIELD", "detail": empty})
            continue
        if r["chunk_id"] not in CHUNK_META.index:
            errors.append({"row": i, "error": "UNKNOWN_CHUNK_ID", "detail": r["chunk_id"]})
            continue
        meta = CHUNK_META.loc[r["chunk_id"]]
        if (meta["document_id"], meta["ITEM_SEQ"], meta["text_hash"]) != (r["document_id"], r["ITEM_SEQ"], r["text_hash"]):
            errors.append({"row": i, "error": "PROVENANCE_MISMATCH", "detail": r["chunk_id"]})
        if hashlib.sha1(str(r["chunk_text"]).encode("utf-8")).hexdigest() != r["text_hash"]:
            errors.append({"row": i, "error": "TEXT_HASH_MISMATCH", "detail": r["chunk_id"]})
        if r["ITEM_SEQ"] not in finding.target_item_seqs:
            errors.append({"row": i, "error": "ITEM_SEQ_NOT_TARGET", "detail": r["ITEM_SEQ"]})
    return errors

