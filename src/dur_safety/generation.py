def _call_openai(system, user, cfg):
    key = get_secret(cfg["api_key_name"])
    if not key:
        return LLMResponse(None, cfg["provider"], cfg["model"], error="LLM_UNAVAILABLE: API key not found")
    t0 = time.time()
    try:
        client = openai.OpenAI(api_key=key, max_retries=cfg["max_retries"], timeout=cfg["timeout_s"])
        resp = client.responses.create(
            model=cfg["model"],
            instructions=system,
            input=user,
            text={"format": {"type": "json_schema", "name": "evidence_grounded_explanation",
                             "schema": OUTPUT_JSON_SCHEMA, "strict": True}},
            max_output_tokens=cfg["max_output_tokens"],
            store=cfg["store"],
        )
    except Exception as e:  # noqa: BLE001
        return LLMResponse(None, cfg["provider"], cfg["model"], latency_s=round(time.time() - t0, 2),
                           error=_redact(f"{type(e).__name__}: {str(e)[:300]}", key))
    texts, refusals = [], []
    for item in resp.output or []:
        for c in getattr(item, "content", None) or []:
            if getattr(c, "type", None) == "output_text":
                texts.append(c.text)
            elif getattr(c, "type", None) == "refusal":
                refusals.append(c.refusal)
    status = resp.status
    if resp.incomplete_details is not None:
        status = f"{status}:{getattr(resp.incomplete_details, 'reason', None)}"
    usage = resp.usage.model_dump() if resp.usage is not None else {}
    return LLMResponse("".join(texts), cfg["provider"], cfg["model"], stop_reason=status,
                       usage={k: v for k, v in usage.items() if isinstance(v, (int, float))},
                       latency_s=round(time.time() - t0, 2),
                       error=f"REFUSAL: {' '.join(refusals)[:300]}" if refusals else None)

