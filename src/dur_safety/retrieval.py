def get_candidates(risk_type, item_seqs):
    """hard filter(ITEM_SEQ) + soft prior 계산. 반환: (candidates DataFrame, info dict)"""
    if risk_type not in RISK_PROFILES:
        raise ValueError(f"알 수 없는 risk_type: {risk_type!r} (허용: {sorted(RISK_PROFILES)})")
    items = [normalize_identifier(s) for s in (item_seqs or [])]
    items = list(dict.fromkeys(s for s in items if s))
    found = [s for s in items if s in ITEM_INDEX]
    info = {"items_requested": items, "items_found": found, "items_missing": [s for s in items if s not in ITEM_INDEX]}
    if not found:
        return corpus.iloc[0:0].copy(), {**info, "n_candidates": 0, "n_candidate_texts": 0, "n_preferred": 0}
    rows = np.concatenate([ITEM_INDEX[s] for s in found])
    cand = corpus.iloc[rows].copy()
    cand["item_order"] = cand["ITEM_SEQ"].map({s: i for i, s in enumerate(found)})
    prof = RISK_PROFILES[risk_type]
    doc_w = cand["doc_type"].astype(str).map(prof["doc_type"]).fillna(0.0)
    cat_w = np.zeros(len(cand))
    for col, w in prof["category"].items():
        cat_w = np.maximum(cat_w, cand[col].to_numpy() * w)
    cand["prior_score"] = (0.5 * doc_w.to_numpy() + 0.5 * cat_w).round(3)
    cand["preferred_article"] = cat_w > 0
    info.update({"n_candidates": int(len(cand)), "n_candidate_texts": int(cand["text_idx"].nunique()),
                 "n_preferred": int(cand["preferred_article"].sum())})
    return cand, info

