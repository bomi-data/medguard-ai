# [nb 04_retrieval.ipynb cell 10] normalize_identifier
def normalize_identifier(value):
    # 02_structured_screening.ipynb 와 동일한 규칙 (입력값 방어용)
    if value is None or isinstance(value, (bool, np.bool_)):
        return None
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        if math.isnan(value) or math.isinf(value) or not float(value).is_integer():
            return None
        return str(int(value))
    if isinstance(value, str):
        text = value.strip()
        if text.lower() in _MISSING_TEXT:
            return None
        if text.replace(".", "", 1).isdigit() and text.endswith(".0"):
            text = text[:-2]
        return text
    return None

