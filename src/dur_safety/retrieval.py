def rank_bm25(query, cand):
    idxs = np.unique(cand["text_idx"].to_numpy())
    s = bm25_scores(query, idxs)
    order = np.argsort(-s, kind="stable")
    hits = [(int(idxs[i]), float(s[i])) for i in order if s[i] > 0]
    return hits

