# [nb 04_retrieval.ipynb cell 26] rrf
def rrf(rank_lists, weights, k):
    fused = defaultdict(float)
    for name, ranked in rank_lists.items():
        for r, idx in enumerate(ranked, start=1):
            fused[idx] += weights[name] / (k + r)
    return fused

# [nb 04_retrieval.ipynb cell 26] balance_by_item
def balance_by_item(ranked_idx, cand):
    """품목별 round-robin (각 text의 대표 품목 기준)"""
    rep_item = cand.sort_values(["item_order", "chunk_id"]).drop_duplicates("text_idx").set_index("text_idx")["item_order"]
    queues = defaultdict(list)
    for i in ranked_idx:
        queues[rep_item[i]].append(i)
    out, keys = [], sorted(queues)
    while any(queues[k] for k in keys):
        for k in keys:
            if queues[k]:
                out.append(queues[k].pop(0))
    return out

