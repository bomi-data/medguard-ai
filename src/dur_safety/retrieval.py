def build_query(finding, include_dur_text=True):
    rt = finding["risk_type"]
    comps = []
    if rt == "elderly_caution":
        comps += [("ingredient", " ".join(finding["ingredient_names"]), "DUR elderly lookup"),
                  ("template", "고령자 노인 투여 시 주의", "template")]
    elif rt == "contraindication":
        names = [n for v in finding["ingredient_names"].values() for n in v]
        comps += [("ingredient", " ".join(names), "DUR contraindication lookup"),
                  ("template", "병용 투여 금기 상호작용", "template")]
        if include_dur_text and finding["dur_text"]:
            comps.append(("dur_reason", " ".join(finding["dur_text"]), "DUR prohbt_content (query only)"))
    elif rt == "therapeutic_duplication":
        comps += [("ingredient", " ".join(finding["ingredient_names"]), "DUR therapeutic lookup"),
                  ("effect_name", finding["effect_name"], "DUR therapeutic lookup"),
                  ("template", "효능 효과", "template")]
    else:
        raise ValueError(rt)
    query = " ".join(c[1] for c in comps if c[1]).strip()
    return query, [{"part": p, "text": t, "source": s} for p, t, s in comps]


