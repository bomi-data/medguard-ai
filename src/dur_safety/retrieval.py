def bm25_scores(query, text_idxs):
    q_terms = np.unique(BM25_VECTORIZER.transform([query]).indices)
    if len(q_terms) == 0 or len(text_idxs) == 0:
        return np.zeros(len(text_idxs))
    tf = BM25_X[text_idxs][:, q_terms].toarray().astype(np.float64)
    k1, b = BM25_PARAMS["k1"], BM25_PARAMS["b"]
    norm = k1 * (1 - b + b * BM25_DL[text_idxs] / BM25_AVGDL)
    return ((tf * (k1 + 1)) / (tf + norm[:, None]) * BM25_IDF[q_terms]).sum(axis=1)

