def retrieve_hybrid(query, risk_type, item_seqs, top_k=5, use_prior=True, balance_items=None):
    """Screening-aware hybrid retrieval. 반환: (results DataFrame, status dict)"""
    cand, info = get_candidates(risk_type, item_seqs)
    base = {"risk_type": risk_type, "query": query, **info}
    empty = pd.DataFrame(columns=RESULT_COLS)
    if not str(query or "").strip():
        return empty, make_status("NO_EVIDENCE", "EMPTY_QUERY", **base)
    if not info["items_found"]:
        return empty, make_status("NO_EVIDENCE", "ITEM_SEQ_NOT_IN_CORPUS", **base)
    if len(cand) == 0:
        return empty, make_status("NO_EVIDENCE", "NO_CANDIDATES", **base)

    bm25_hits = rank_bm25(query, cand)[:HYBRID_PARAMS["bm25_depth"]]
    lists = {"bm25": [i for i, _ in bm25_hits]}
    scores = {"bm25_score": {i: round(s, 4) for i, s in bm25_hits},
              "bm25_rank": {i: r for r, (i, _) in enumerate(bm25_hits, 1)}}
    warnings = []
    if dense_available():
        dense_hits = rank_dense(query, cand)[:HYBRID_PARAMS["dense_depth"]]
        lists["dense"] = [i for i, _ in dense_hits]
        scores["dense_score"] = {i: round(s, 4) for i, s in dense_hits}
        scores["dense_rank"] = {i: r for r, (i, _) in enumerate(dense_hits, 1)}
    else:
        warnings.append("DENSE_UNAVAILABLE")
    if not any(lists.values()):
        return empty, make_status("NO_EVIDENCE", "NO_LEXICAL_MATCH_AND_NO_DENSE", **base)

    pool = set().union(*map(set, lists.values()))
    prior = cand.groupby("text_idx")["prior_score"].max()
    scores["prior_score"] = prior.to_dict()
    if use_prior:
        # 같은 prior 값끼리는 BM25 순위로 정렬 (결정적 tie-break)
        bm25_pos = scores["bm25_rank"]
        lists["prior"] = sorted((i for i in pool if prior.get(i, 0) > 0),
                                key=lambda i: (-prior[i], bm25_pos.get(i, 10**9), i))
    fused = rrf(lists, HYBRID_PARAMS["weights"], HYBRID_PARAMS["rrf_k"])
    ranked = sorted(pool, key=lambda i: (-fused[i], i))
    if balance_items is None:
        balance_items = HYBRID_PARAMS["item_balance_for_multi_item"] and len(info["items_found"]) > 1
    if balance_items:
        ranked = balance_by_item(ranked, cand)
    scores["hybrid_score"] = {i: round(fused[i], 6) for i in ranked}
    scores["hybrid_rank"] = {i: r for r, i in enumerate(ranked, 1)}

    res = build_results(cand, ranked, "hybrid" if "dense" in lists else "hybrid_bm25_only", risk_type, top_k, scores)
    if info["n_preferred"] == 0:
        warnings.append("NO_RISK_SPECIFIC_ARTICLE")          # 예: 노인주의 약물인데 고령자 조항 없음
    if info["items_missing"]:
        warnings.append("SOME_ITEM_SEQ_NOT_IN_CORPUS")
    lexical_support = int(res["bm25_score"].notna().sum()) if len(res) else 0
    status = "OK" if "dense" in lists else "DEGRADED"
    return res, make_status(status, None, warnings=warnings, lexical_support_in_topk=lexical_support,
                            preferred_in_topk=int(res["article_category"].isin(["elderly", "interaction", "contraindication"]).sum()),
                            **base)

