# [nb 02_structured_screening.ipynb cell 13] normalize_identifier
def normalize_identifier(value):
    # item_seq 1개를 문자열로 정규화합니다. 결측/무효 값은 None을 반환합니다.
    if value is None:
        return None
    if isinstance(value, (bool, np.bool_)):
        return None
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        if math.isnan(value) or math.isinf(value) or not float(value).is_integer():
            return None
        return str(int(value))
    if isinstance(value, str):
        text = value.strip()
        if text.lower() in _MISSING_TEXT:
            return None
        # "201404127.0" 처럼 소수점 0만 붙은 문자열 처리
        if text.replace(".", "", 1).isdigit() and text.endswith(".0"):
            text = text[:-2]
        return text
    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass
    return None

