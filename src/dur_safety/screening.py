# [nb 02_structured_screening.ipynb cell 28] normalize_medication_list
def normalize_medication_list(medications):
    if medications is None:
        medications = []
    if isinstance(medications, (str, bytes, int, float)):
        raise TypeError(
            "medications는 item_seq의 리스트여야 합니다. 예: ['201404127', '201508404']\n"
            f"받은 값: {medications!r}"
        )

    normalized, invalid_inputs, seen, duplicated = [], [], set(), set()
    for raw_value in medications:
        item_seq = normalize_identifier(raw_value)
        if item_seq is None:
            invalid_inputs.append(repr(raw_value))
            continue
        if item_seq in seen:
            duplicated.add(item_seq)
            continue
        seen.add(item_seq)
        normalized.append(item_seq)

    return {
        "normalized": sorted(normalized),
        "duplicate_inputs": sorted(duplicated),
        "invalid_inputs": invalid_inputs,
    }

# [nb 02_structured_screening.ipynb cell 30] build_contraindication_record
def build_contraindication_record(item_a, item_b, include_evidence=True):
    drug_1, drug_2, pair_id = make_canonical_pair(item_a, item_b)
    record = {
        "risk_type": "contraindication",
        "rule_source": "DUR 병용금기",
        "canonical_pair_id": pair_id,
        "drug_1_item_seq": drug_1,
        "drug_1_item_name": get_drug_name(drug_1),
        "drug_2_item_seq": drug_2,
        "drug_2_item_name": get_drug_name(drug_2),
        "evidence_lookup_key": pair_id,
    }
    if include_evidence:
        evidence = get_contraindication_evidence(pair_id)
        record.update({
            "has_evidence": evidence["has_evidence"],
            "evidence_count": evidence["evidence_count"],
            "evidence_ids": evidence["evidence_ids"],
            "evidence_dur_seqs": evidence["dur_seqs"],
            "prohbt_contents": evidence["prohbt_contents"],
        })
    return record

# [nb 02_structured_screening.ipynb cell 30] check_contraindications
def check_contraindications(medications, include_evidence=True):
    meds = normalize_medication_list(medications)["normalized"]
    findings = []
    for item_a, item_b in combinations(meds, 2):
        _, _, pair_id = make_canonical_pair(item_a, item_b)
        if pair_id in CONTRAINDICATION_PAIR_IDS:
            findings.append(build_contraindication_record(item_a, item_b, include_evidence))
    return sorted(findings, key=lambda r: r["canonical_pair_id"])

