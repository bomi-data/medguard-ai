def normalize_identifier_series(series):
    # dataframe 컬럼 전체를 정규화합니다. 결과 dtype은 pandas 'string' (결측은 <NA>).
    as_object = series.astype("object")
    unique_values = as_object.dropna().unique()
    mapping = {v: normalize_identifier(v) for v in unique_values}
    return as_object.map(mapping).astype("string")

