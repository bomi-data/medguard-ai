def check_therapeutic_duplication(medications):
    meds = normalize_medication_list(medications)["normalized"]

    items_by_effect = defaultdict(set)
    for item_seq in meds:
        for effect_name in THERAPEUTIC_EFFECTS_BY_ITEM.get(item_seq, set()):
            items_by_effect[effect_name].add(item_seq)

    findings = []
    for effect_name in sorted(items_by_effect):
        matched = sorted(items_by_effect[effect_name])
        if len(matched) < 2:
            continue

        matched_items, all_ingr_codes, all_texts = [], set(), set()
        for item_seq in matched:
            detail = THERAPEUTIC_DETAIL.get((item_seq, effect_name), {})
            matched_items.append({
                "item_seq": item_seq,
                "item_name": detail.get("item_name") or get_drug_name(item_seq),
                "ingr_codes": detail.get("ingr_codes", []),
                "ingredient_names": detail.get("ingredient_names", []),
                "sers_names": detail.get("sers_names", []),
                "dur_seqs": detail.get("dur_seqs", []),
                "source_record_count": detail.get("source_record_count", 0),
            })
            all_ingr_codes.update(detail.get("ingr_codes", []))
            all_texts.update(detail.get("prohbt_contents", []))

        findings.append({
            "risk_type": "therapeutic_duplication",
            "rule_source": "DUR 효능군중복",
            "effect_name": effect_name,
            "matched_item_seqs": matched,
            "matched_count": len(matched),
            "matched_items": matched_items,
            "distinct_ingr_code_count": len(all_ingr_codes),
            "has_prohbt_content": len(all_texts) > 0,
            "prohbt_contents": sorted(all_texts),
        })
    return findings

