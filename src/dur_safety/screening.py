# [nb 02_structured_screening.ipynb cell 15] make_canonical_pair
def make_canonical_pair(item_a, item_b):
    # 순서와 무관한 (unordered) pair를 (작은값, 큰값, "작은값|큰값")으로 반환
    first, second = sorted([item_a, item_b])
    return first, second, f"{first}|{second}"

# [nb 02_structured_screening.ipynb cell 21] clean_value
def clean_value(value):
    if value is None:
        return None
    try:
        if pd.isna(value):
            return None
    except (TypeError, ValueError):
        pass
    if isinstance(value, str):
        value = value.strip()
        return value if value else None
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        return float(value)
    if isinstance(value, (np.bool_,)):
        return bool(value)
    return value

